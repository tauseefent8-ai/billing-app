class _UsersScreenState extends State<UsersScreen> {
  String search = "";
  TextEditingController searchCtrl = TextEditingController();

  @override
  void initState() {
    super.initState();
    _loadMT();
    WidgetsBinding.instance.addPostFrameCallback((_) {
      _autoGenerateExpiredBillsSilent();
    });
  }

  Future<void> _loadMT() async {
    var p = await SharedPreferences.getInstance();
    String ip = p.getString('mt_ip')?? "";
    String user = p.getString('mt_user')?? "";
    String pass = p.getString('mt_pass')?? "";
    String port = p.getString('mt_port')?? "80";
    if (ip.isNotEmpty && user.isNotEmpty) {
      MikrotikService.setCreds(ip: ip, port: port, username: user, password: pass);
    }
  }

  List<dynamic> get filtered {
    return widget.users.where((u){
      if(search.isEmpty) return true;
      return u['name'].toString().toLowerCase().contains(search.toLowerCase()) || u['phone'].toString().contains(search);
    }).toList();
  }

  Future<void> _autoGenerateExpiredBillsSilent() async {
    DateTime now = DateTime.now();
    String currentMonthKey = "${now.year}-${now.month}";
    List<Map<String,dynamic>> newBillsBatch = [];
    List<Map<String,dynamic>> expiredActiveUsers = [];
    for (var user in widget.users) {
      bool isExpired = false;
      if (user['expiryDate']!= null) {
        try {
          DateTime expiryDate = DateTime.fromMillisecondsSinceEpoch(user['expiryDate']);
          if (now.isAfter(expiryDate)) isExpired = true;
        } catch (e) {}
      }
      if (isExpired) {
        if ((user['status']??'disabled') == 'active') expiredActiveUsers.add(user);
        String cleanPhone = user['phone'].toString().replaceAll(RegExp(r'[^0-9]'), '');
        bool billExists = widget.bills.any((b) => b['phone'].toString().replaceAll(RegExp(r'[^0-9]'), '') == cleanPhone && b['billMonth'] == currentMonthKey);
        if (!billExists) {
          int monthlyAmount = FirebaseService.parseAmount(user['amount']?? 1000);
          int previousDue = FirebaseService.parseAmount(user['pendingDue']?? 0);
          int total = monthlyAmount + previousDue;
          var newBill = {
            'name': user['name'], 'phone': cleanPhone, 'raw_phone': user['raw_phone']?? cleanPhone,
            'username': user['username']?? '', 'amount': monthlyAmount, 'dueAmount': previousDue,
            'totalAmount': total, 'pendingDue': previousDue, 'package': user['package']?? '10 Mbps',
            'isPaid': false, 'isPartial': false, 'paidAmount': 0, 'remainingDue': total,
            'date': now.toIso8601String(), 'billMonth': currentMonthKey,
            'createdAt': now.millisecondsSinceEpoch, 'autoGenerated': true, 'status': 'pending',
            'id': FirebaseService.genBillId(user['phone'].toString(), currentMonthKey)
          };
          newBillsBatch.add(newBill);
        }
      }
    }
    if (newBillsBatch.isNotEmpty) {
      try {
        await FirebaseService.batchWriteBills(newBillsBatch);
        if (mounted) { setState(() { widget.bills.addAll(newBillsBatch); }); widget.onBillsUpdate(); }
      } catch (e) {}
    }
    for (var u in expiredActiveUsers) {
      String username = u['username']?.toString()?? u['pppoe_username']?.toString()?? '';
      if (username.isEmpty) continue;
      try {
        var result = await MikrotikService.disableUser(username).timeout(Duration(seconds: 6), onTimeout: () => {'ok': false, 'msg': 'timeout'});
        if (result['ok'] == true) {
          String cleanPhone = u['phone'].toString().replaceAll(RegExp(r'[^0-9]'), '');
          await FirebaseService.usersCol.doc(cleanPhone).update({'status': 'disabled', 'autoDisabledReason': 'expired', 'autoDisabledAt': now.millisecondsSinceEpoch}).catchError((_) {});
          if (mounted) setState(() { u['status'] = 'disabled'; });
        }
      } catch (_) {}
    }
    if (expiredActiveUsers.isNotEmpty && mounted) widget.onUsersUpdate();
  }

  Future<void> _deleteUserFully(Map<String, dynamic> u) async {
    String cleanPhone = u['phone'].toString().replaceAll(RegExp(r'[^0-9]'), '');
    String username = u['username']?.toString()?? u['pppoe_username']?.toString()?? '';
    String name = u['name']?.toString()?? 'User';
    if (mounted) {
      showDialog(context: context, barrierDismissible: false, builder: (c) => Dialog(
        backgroundColor: Color(0xFF1E1E1E), shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(16)),
        child: Padding(padding: EdgeInsets.all(20), child: Column(mainAxisSize: MainAxisSize.min, children: [
          CircularProgressIndicator(color: Colors.redAccent), SizedBox(height: 12),
          Text("Deleting $name...", style: GoogleFonts.poppins(color: Colors.white, fontSize: 12, fontWeight: FontWeight.bold)),
          SizedBox(height: 4), Text("MikroTik + Firebase + App", style: GoogleFonts.poppins(color: Colors.white54, fontSize: 10)),
        ])),
      ));
    }
    try { if (username.isNotEmpty) { try { await MikrotikService.deleteUser(username).timeout(Duration(seconds: 8), onTimeout: () => {'ok': true}); } catch (_) { await MikrotikService.disableUser(username).timeout(Duration(seconds: 8), onTimeout: () => {'ok': true}); } } } catch (e) { debugPrint("MikroTik delete ignored: $e"); }
    try { await FirebaseService.usersCol.doc(cleanPhone).delete().timeout(Duration(seconds: 10)); } catch (e) { try{ await FirebaseFirestore.instance.collection('users').doc(cleanPhone).delete(); }catch(_){} }
    try { Provider.of<AppProvider>(context, listen: false).removeUserLocal(cleanPhone); } catch (_) {}
    try { widget.users.removeWhere((element) => element['phone'].toString().replaceAll(RegExp(r'[^0-9]'), '') == cleanPhone); } catch (_) {}
    widget.onUsersUpdate();
    if (mounted) { Navigator.pop(context); ScaffoldMessenger.of(context).showSnackBar(SnackBar(content: Text("$name delete ho gaya"), backgroundColor: Colors.green)); }
  }

