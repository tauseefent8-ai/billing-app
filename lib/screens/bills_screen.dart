        SizedBox(height: 16),
        SizedBox(width: double.infinity, child: OutlinedButton.icon(icon: Icon(Icons.picture_as_pdf, color: Colors.white70), label: Text("PDF Receipt - Share", style: GoogleFonts.poppins(color: Colors.white70, fontSize: 12)), style: OutlinedButton.styleFrom(side: BorderSide(color: Colors.white24), padding: EdgeInsets.symmetric(vertical: 14), shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(12))), onPressed: ()=> _showBillPdf(context))),
        SizedBox(height: 30),
      ])),
    );
  }
