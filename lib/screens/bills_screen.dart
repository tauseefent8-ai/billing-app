class PaidBillViewOnlyScreen extends StatelessWidget {
  final Map<String, dynamic> bill;
  final Map<String, dynamic>? user;
  const PaidBillViewOnlyScreen({super.key, required this.bill, this.user});
  String _formatExpiry(dynamic ms){ try{ DateTime d = DateTime.fromMillisecondsSinceEpoch(ms); return "${d.day}/${d.month}/${d.year}"; }catch(e){ return ms.toString(); } }

  Future<void> _showBillPdf(BuildContext context) async {
    final pdf = pw.Document();
    String expiryStr = user!= null && user!['expiryDate']!= null? (){ try{ DateTime d = DateTime.fromMillisecondsSinceEpoch(user!['expiryDate']); return "${d.day}/${d.month}/${d.year}"; }catch(e){ return "-"; }}() : "-";
    pdf.addPage(pw.Page(pageFormat: PdfPageFormat.a4, build: (pw.Context ctx) => pw.Column(crossAxisAlignment: pw.CrossAxisAlignment.start, children: [
      pw.Container(color: PdfColors.green, padding: pw.EdgeInsets.all(16), child: pw.Row(mainAxisAlignment: pw.MainAxisAlignment.spaceBetween, children: [pw.Text(AppStrings.company, style: pw.TextStyle(color: PdfColors.white, fontSize: 22, fontWeight: pw.FontWeight.bold)), pw.Text("PAID BILL RECEIPT", style: pw.TextStyle(color: PdfColors.white, fontSize: 14, fontWeight: pw.FontWeight.bold))])),
      pw.SizedBox(height: 20), pw.Text("Customer Details", style: pw.TextStyle(fontSize: 14, fontWeight: pw.FontWeight.bold)), pw.Divider(),
      pw.Text("Name: ${bill['name']}"), pw.Text("Phone: ${bill['raw_phone']?? bill['phone']}"), pw.Text("Username: ${bill['username']?? user?['username']?? '-'}"), pw.Text("Package: ${bill['package']}"), pw.Text("Bill Month: ${bill['billMonth']}"), pw.Text("Expiry: $expiryStr"), pw.SizedBox(height: 10),
      pw.Text("Amount Details", style: pw.TextStyle(fontSize: 14, fontWeight: pw.FontWeight.bold)), pw.Divider(),
      pw.Text("Total Amount: Rs. ${bill['totalAmount']?? bill['amount']}"), pw.Text("Paid Amount: Rs. ${bill['paidAmount']?? bill['totalAmount']}"), pw.Text("Status: PAID"),
      pw.SizedBox(height: 20), pw.Text("Thank you! Bill Paid.", style: pw.TextStyle(fontSize: 12, color: PdfColors.green)),
    ])));
    await Printing.layoutPdf(onLayout: (format) async => pdf.save());
  }

  Widget _row(String label, String value, {bool bold=false, Color? color}){
    return Padding(padding: EdgeInsets.symmetric(vertical: 4), child: Row(mainAxisAlignment: MainAxisAlignment.spaceBetween, children: [Text(label, style: GoogleFonts.poppins(color: Colors.white54, fontSize: 11)), Text(value, style: GoogleFonts.poppins(color: color?? Colors.white, fontSize: bold? 13 : 11, fontWeight: bold? FontWeight.bold : FontWeight.w600))]));
  }

