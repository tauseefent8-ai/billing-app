class BillsScreen extends StatefulWidget {
  final List<dynamic> bills;
  final List<dynamic> users;
  final List<dynamic> collections;
  final VoidCallback onUpdate;
  final VoidCallback onUsersUpdate;
  final Function(Map<String, dynamic>) onCollectionAdd;
  final Function(String) onCollectionRemove;
  const BillsScreen({super.key, required this.bills, required this.users, this.collections = const [], required this.onUpdate, required this.onUsersUpdate, required this.onCollectionAdd, required this.onCollectionRemove});
  @override
  State<BillsScreen> createState() => _BillsScreenState();
}

class _BillsScreenState extends State<BillsScreen> {
  String filter = "All";
  String search = "";
  String selectedMonthFilter = "${DateTime.now().year}-${DateTime.now().month}";
  final TextEditingController searchCtrl = TextEditingController();
  bool isGenerating = false;
  Map<String, dynamic>? _lastDeletedBill;
  int _lastDeletedBillIndex = -1;

  List<dynamic> get filteredBills => widget.bills.where((b) {
    bool isPending = b['isPaid']!= true;
    bool matchFilter = filter == "All" || (filter == "Pending" && b['isPaid']!= true && b['isPartial']!=true) || (filter == "Partial" && (b['isPartial']==true));
    bool matchSearch = search.isEmpty || b['name'].toString().toLowerCase().contains(search.toLowerCase()) || b['phone'].toString().contains(search);
    bool matchMonth = true;
    return isPending && matchFilter && matchSearch && matchMonth;
  }).toList();

  List<dynamic> get paidBills => widget.bills.where((b) => b['isPaid'] == true).toList();

  List<String> get last12Months {
    List<String> months = [];
    DateTime now = DateTime.now();
    for(int i=0; i<12; i++){
      DateTime d = DateTime(now.year, now.month - i, 1);
      months.add("${d.year}-${d.month}");
    }
    return months;
  }

  Future<void> autoGenerateExpiredBills() async {
    if(isGenerating) return;
    setState(()=> isGenerating = true);
    DateTime now = DateTime.now();
    String currentMonthKey = "${now.year}-${now.month}";
    List<Map<String,dynamic>> newBillsBatch = [];
    List<Map<String,dynamic>> expiredActiveUsers = [];
    for (var user in widget.users) {
      bool isExpired = false;
      if (user['expiryDate']!= null) {
        try { DateTime expiryDate = DateTime.fromMillisecondsSinceEpoch(user['expiryDate']); if (now.isAfter(expiryDate)) isExpired = true; } catch (e) {}
      }
      if (isExpired) {
        if ((user['status']??'disabled') == 'active') { expiredActiveUsers.add(user); }
        String cleanPhone = user['phone'].toString().replaceAll(RegExp(r'[^0-9]'), '');
        bool billExists = widget.bills.any((b) => b['phone'].toString().replaceAll(RegExp(r'[^0-9]'), '') == cleanPhone && b['billMonth'] == currentMonthKey);
        if (!billExists) {
          int monthlyAmount = FirebaseService.parseAmount(user['amount']?? 1000);
          int previousDue = FirebaseService.parseAmount(user['pendingDue']?? 0);
          int total = monthlyAmount + previousDue;
          var newBill = {'name': user['name'],'phone': cleanPhone,'raw_phone': user['raw_phone']?? cleanPhone,'username': user['username']?? '','amount': monthlyAmount,'dueAmount': previousDue,'totalAmount': total,'package': user['package']?? '10 Mbps','isPaid': false,'isPartial': false,'paidAmount': 0,'remainingDue': total,'date': now.toIso8601String(),'billMonth': currentMonthKey,'createdAt': now.millisecondsSinceEpoch,'autoGenerated': true,'id': FirebaseService.genBillId(user['phone'].toString(), currentMonthKey)};
          newBillsBatch.add(newBill);
        }
      }
    }
    if(newBillsBatch.isNotEmpty){
      try{
        await FirebaseService.batchWriteBills(newBillsBatch);
        setState(()=> widget.bills.addAll(newBillsBatch));
        widget.onUpdate();
        if(mounted) ScaffoldMessenger.of(context).showSnackBar(SnackBar(content: Text("${newBillsBatch.length} bills generate"), backgroundColor: Colors.green));
      }catch(e){
        if(mounted) ScaffoldMessenger.of(context).showSnackBar(SnackBar(content: Text("Error: $e"), backgroundColor: Colors.red));
      }
    }
    int disconnectedCount = 0;
    for(var u in expiredActiveUsers){
      String username = u['username']?.toString()?? u['pppoe_username']?.toString()?? '';
      if(username.isEmpty) continue;
      try{
        var result = await MikrotikService.disableUser(username).timeout(Duration(seconds: 7), onTimeout: ()=> {'ok': false});
        if(result['ok']==true){
          String cleanPhone = u['phone'].toString().replaceAll(RegExp(r'[^0-9]'), '');
          await FirebaseService.usersCol.doc(cleanPhone).update({'status': 'disabled', 'autoDisabledReason': 'expired', 'autoDisabledAt': now.millisecondsSinceEpoch}).catchError((_){});
          setState(()=> u['status']='disabled');
          disconnectedCount++;
        }
      }catch(_){}
    }
    if(disconnectedCount>0){ widget.onUsersUpdate(); if(mounted) ScaffoldMessenger.of(context).showSnackBar(SnackBar(content: Text("$disconnectedCount users auto disconnect"), backgroundColor: Colors.orange)); }
    setState(()=> isGenerating = false);
  }

  void _openBillDetail(Map<String, dynamic> bill) {
    String cleanPhone = bill['phone'].toString().replaceAll(RegExp(r'[^0-9]'), '');
    Map<String, dynamic>? user;
    try { user = widget.users.firstWhere((u) => u['phone'].toString().replaceAll(RegExp(r'[^0-9]'), '') == cleanPhone); } catch (e) { user = null; }
    Navigator.push(context, MaterialPageRoute(builder: (_) => BillDetailScreen(bill: bill, user: user!= null? Map<String, dynamic>.from(user) : null, users: widget.users, onUpdate: widget.onUpdate, onUsersUpdate: widget.onUsersUpdate, onCollectionAdd: widget.onCollectionAdd,))).then((_) { setState(() {}); widget.onUpdate(); widget.onUsersUpdate(); });
  }

  void _openPaidHistory() {
    Navigator.push(context, MaterialPageRoute(builder: (_) => PaidBillsHistoryScreen(paidBills: paidBills, users: widget.users)));
  }

  Future<void> _confirmDeleteBill(Map<String, dynamic> bill) async {
    bool confirm = await showDialog(context: context, builder: (ctx)=> AlertDialog(backgroundColor: Color(0xFF1E1E1E), title: Text("Bill Delete?", style: GoogleFonts.poppins(color: Colors.white, fontSize: 13, fontWeight: FontWeight.bold)), content: Text("${bill['name']} - Rs.${bill['totalAmount']?? bill['amount']} delete + UNDO?", style: GoogleFonts.poppins(color: Colors.white70, fontSize: 11)), actions: [TextButton(onPressed: ()=> Navigator.pop(ctx,false), child: Text("Nahi")), ElevatedButton(style: ElevatedButton.styleFrom(backgroundColor: Colors.redAccent), onPressed: ()=> Navigator.pop(ctx,true), child: Text("Haan Delete"))]))?? false;
    if(!confirm) return; await _deleteBillWithUndo(bill);
  }

  Future<void> _deleteBillWithUndo(Map<String, dynamic> bill) async {
    _lastDeletedBill = Map<String, dynamic>.from(bill);
    _lastDeletedBillIndex = widget.bills.indexWhere((b)=> b['id']==bill['id']);
    setState(()=> widget.bills.removeWhere((b)=> b['id']==bill['id']));
    try{
      await FirebaseService.billsCol.doc(bill['id']).delete();
      try{ await FirebaseService.collectionsCol.doc(bill['id']).delete(); widget.onCollectionRemove(bill['id']); }catch(_){}
      var colSnap = await FirebaseService.collectionsCol.where('billId', isEqualTo: bill['id']).get();
      for(var d in colSnap.docs){ try{ await d.reference.delete(); widget.onCollectionRemove(d.id); }catch(_){} }
    }catch(e){ if(_lastDeletedBill!=null){ setState(()=> widget.bills.insert(_lastDeletedBillIndex>=0? _lastDeletedBillIndex : 0, _lastDeletedBill!)); } return; }
    widget.onUpdate();
    if(!mounted) return;
    ScaffoldMessenger.of(context).showSnackBar(SnackBar(content: Text("Bill delete - UNDO 5 sec"), backgroundColor: Color(0xFF1E1E1E), duration: Duration(seconds: 5), action: SnackBarAction(label: "UNDO", textColor: Color(0xFF7C4DFF), onPressed: () async { if(_lastDeletedBill==null) return; try{ await FirebaseService.billsCol.doc(_lastDeletedBill!['id']).set(_lastDeletedBill!); setState(()=> widget.bills.insert(_lastDeletedBillIndex>=0? _lastDeletedBillIndex : 0, _lastDeletedBill!)); widget.onUpdate(); _lastDeletedBill = null; }catch(e){} })));
  }

  @override
  Widget build(BuildContext context) {
    int remainingAmount = filteredBills.fold(0, (s,b)=> s + FirebaseService.parseAmount(b['remainingDue']?? (b['isPaid']==true? 0 : b['totalAmount']?? b['amount'])));
    return Scaffold(
      backgroundColor: Color(0xFF121212),
      appBar: AppBar(backgroundColor: Color(0xFF121212), elevation: 0, title: Column(crossAxisAlignment: CrossAxisAlignment.start, children: [Text("Bills - Pending", style: GoogleFonts.poppins(color: Colors.white, fontSize: 14, fontWeight: FontWeight.bold)), Text("Baqaya Rs.$remainingAmount • ${paidBills.length} Paid", style: GoogleFonts.poppins(color: Colors.white54, fontSize: 8))]), actions: [
        Container(margin: EdgeInsets.only(right: 6), decoration: BoxDecoration(color: Color(0xFF00C853).withOpacity(0.2), borderRadius: BorderRadius.circular(10)), child: IconButton(icon: Icon(Icons.history, color: Color(0xFF00C853), size: 20), tooltip: "Paid Bills History", onPressed: _openPaidHistory)),
        Container(margin: EdgeInsets.only(right: 8), decoration: BoxDecoration(color: isGenerating? Colors.grey : Color(0xFF7C4DFF), borderRadius: BorderRadius.circular(10)), child: IconButton(icon: isGenerating? SizedBox(width: 14, height: 14, child: CircularProgressIndicator(strokeWidth: 2, color: Colors.white)) : Icon(Icons.wifi_off_rounded, color: Colors.white, size: 18), tooltip: "Auto Generate", onPressed: isGenerating? null : autoGenerateExpiredBills)),
      ]),
      body: Column(children: [
        Container(margin: EdgeInsets.all(12), padding: EdgeInsets.all(14), decoration: BoxDecoration(color: Color(0xFF1E1E1E), borderRadius: BorderRadius.circular(16), border: Border.all(color: Colors.white10)), child: Row(mainAxisAlignment: MainAxisAlignment.spaceBetween, children: [Text("Pending Baqaya: Rs.$remainingAmount", style: GoogleFonts.poppins(color: Colors.redAccent, fontWeight: FontWeight.bold, fontSize: 11)), GestureDetector(onTap: _openPaidHistory, child: Container(padding: EdgeInsets.symmetric(horizontal: 10, vertical: 5), decoration: BoxDecoration(color: Color(0xFF00C853), borderRadius: BorderRadius.circular(8)), child: Text("Paid History (${paidBills.length})", style: GoogleFonts.poppins(color: Colors.white, fontSize: 9, fontWeight: FontWeight.bold))))])),
        Padding(padding: EdgeInsets.symmetric(horizontal: 12), child: Container(decoration: BoxDecoration(color: Color(0xFF1E1E1E), borderRadius: BorderRadius.circular(12)), child: TextField(controller: searchCtrl, style: TextStyle(color: Colors.white, fontSize: 12), onChanged: (v)=> setState(()=> search=v), decoration: InputDecoration(hintText: "Search pending bill...", prefixIcon: Icon(Icons.search, color: Colors.white54, size: 18), border: OutlineInputBorder(borderRadius: BorderRadius.circular(12), borderSide: BorderSide.none))))),
        SizedBox(height: 10),
        Expanded(child: filteredBills.isEmpty? Center(child: Column(mainAxisAlignment: MainAxisAlignment.center, children: [Icon(Icons.check_circle, color: Colors.green, size: 40), SizedBox(height: 8), Text("Koi pending bill nahi", style: GoogleFonts.poppins(color: Colors.white54)), SizedBox(height: 4), Text("Paid bills dekhne ke liye upar History button dabao", style: GoogleFonts.poppins(color: Colors.white38, fontSize: 10))])) : ListView.builder(itemCount: filteredBills.length, itemBuilder: (c,i){
          var b = filteredBills[i]; bool isPartial = b['isPartial']==true; int totalAmt = FirebaseService.parseAmount(b['totalAmount']?? b['amount']); int remainAmt = FirebaseService.parseAmount(b['remainingDue']?? totalAmt); Color borderColor = isPartial? Color(0xFFFF9100) : Color(0xFFFF1744);
          return Container(margin: EdgeInsets.symmetric(horizontal: 12, vertical: 5), decoration: BoxDecoration(color: Color(0xFF1E1E1E), borderRadius: BorderRadius.circular(14), border: Border(left: BorderSide(color: borderColor, width: 4))), child: ListTile(onTap: ()=> _openBillDetail(b), leading: Container(width: 44, height: 44, decoration: BoxDecoration(color: borderColor.withOpacity(0.15), borderRadius: BorderRadius.circular(10)), child: Icon(Icons.wifi_off, color: borderColor)), title: Text(b['name'].toString(), style: GoogleFonts.poppins(color: Colors.white, fontSize: 12, fontWeight: FontWeight.bold)), subtitle: Text("Total Rs.$totalAmt • Baqaya Rs.$remainAmt • ${b['billMonth']}", style: GoogleFonts.poppins(color: Colors.white54, fontSize: 9)), trailing: Row(mainAxisSize: MainAxisSize.min, children: [IconButton(icon: Icon(Icons.delete_outline_rounded, color: Colors.white38, size: 18), onPressed: ()=> _confirmDeleteBill(b)), Icon(Icons.arrow_forward_ios, color: Colors.white24, size: 14)])));
        })),
      ]),
    );
  }
}

