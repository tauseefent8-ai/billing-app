          Row(children: [CircleAvatar(backgroundColor: Color(0xFF00C853), radius: 28, child: Text(bill['name'].toString().isNotEmpty? bill['name'].toString()[0].toUpperCase() : "U", style: TextStyle(color: Colors.white, fontWeight: FontWeight.bold, fontSize: 20))), SizedBox(width: 12), Expanded(child: Column(crossAxisAlignment: CrossAxisAlignment.start, children: [Text(bill['name']?? '-', style: GoogleFonts.poppins(color: Colors.white, fontSize: 16, fontWeight: FontWeight.bold)), Text("${bill['phone']} | ${bill['package']}", style: GoogleFonts.poppins(color: Colors.white54, fontSize: 11)), Text("Bill Month: ${bill['billMonth']}", style: GoogleFonts.poppins(color: Colors.white38, fontSize: 10))])), Container(padding: EdgeInsets.symmetric(horizontal: 10, vertical: 6), decoration: BoxDecoration(color: Colors.green.withOpacity(0.2), borderRadius: BorderRadius.circular(10)), child: Text("Paid", style: GoogleFonts.poppins(color: Colors.green, fontSize: 11, fontWeight: FontWeight.bold)))]),
