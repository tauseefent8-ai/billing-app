    int totalAmt = FirebaseService.parseAmount(bill['totalAmount']?? bill['amount']);
    int paidAmt = FirebaseService.parseAmount(bill['paidAmount']?? totalAmt);
    int dueAmt = FirebaseService.parseAmount(bill['dueAmount']?? 0);
    return Scaffold(
      backgroundColor: Color(0xFF121212),
      appBar: AppBar(backgroundColor: Color(0xFF121212), title: Text("Paid Bill Details", style: GoogleFonts.poppins(color: Colors.white, fontSize: 14, fontWeight: FontWeight.bold)), actions: [IconButton(icon: Icon(Icons.picture_as_pdf, color: Colors.white70), onPressed: ()=> _showBillPdf(context))]),
